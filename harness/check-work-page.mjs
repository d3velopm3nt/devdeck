import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})})
const page = await browser.newPage({viewport:{width:1500,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
const button=name=>page.getByRole('button',{name,exact:true})
const calls=()=>page.evaluate(()=>window.__workCalls)
await mkdir('test-results/work-redesign',{recursive:true})
try {
  await page.goto(`${process.env.HARNESS_URL||'http://127.0.0.1:5202'}/harness/work-page.html`)
  await page.getByRole('heading',{name:'Existing request survives'}).waitFor()
  await page.getByRole('heading',{name:'Software Factory lifecycle pilot'}).waitFor()
  assert.equal(await button('Runs').count(),0)
  await page.screenshot({path:'test-results/work-redesign/board.png',fullPage:true})
  await button('Goals').click()
  await page.locator('.wh-goal-ring').first().waitFor()
  await page.locator('.wh-goal-visual').first().click()
  await page.getByRole('region',{name:'Goal delivery map'}).waitFor()
  await page.screenshot({path:'test-results/work-redesign/goals.png',fullPage:true})
  await button('Work Items').click()
  await button('New work item').click()
  await page.getByLabel('Work item title',{exact:true}).fill('Verify the delivery lifecycle')
  await page.getByLabel('Work item description',{exact:true}).fill('## Request\nMake the lifecycle observable.')
  await page.getByLabel('Work item acceptance criteria',{exact:true}).fill('- [ ] Evidence is inspectable')
  await button('Save work item').click()
  await page.getByRole('region',{name:'Work item details'}).waitFor()
  await page.getByLabel('Workflow for this work item').selectOption('3:factory')
  await button('Add workflow run').click()
  await page.getByRole('region',{name:'Work item workflow run'}).waitFor()
  await button('← Verify the delivery lifecycle').click()
  await page.getByLabel('Workflow for this work item').selectOption('3:docs')
  await button('Add workflow run').click()
  await button('← Verify the delivery lifecycle').click()
  await page.getByText('2 attached',{exact:true}).waitFor()
  assert.equal((await calls()).filter(c=>c.command==='attach').length,2)
  assert((await calls()).every(c=>!c.command.includes('start')))
  await button('Edit work item').click()
  await page.getByLabel('Work item state',{exact:true}).selectOption('completed')
  await button('Save work item').click()
  await page.getByRole('alert').filter({hasText:'Accept or resolve'}).waitFor()
  await button('Cancel').click()
  await page.evaluate(()=>window.__setRunState('running'))
  await page.getByRole('region',{name:'Work item details'}).getByText('working',{exact:true}).waitFor()
  await page.screenshot({path:'test-results/work-redesign/item-runs.png',fullPage:true})
  await page.evaluate(()=>window.__setRunState('review'))
  await button('Refresh Work').click()
  const reviewGate=page.getByRole('region',{name:'Review Plan',exact:true})
  await reviewGate.waitFor()
  assert.equal(await reviewGate.getByRole('button',{name:'Approve step'}).isDisabled(),true)
  await reviewGate.getByLabel('Review notes for Plan',{exact:true}).fill('Clarify the handoff evidence.')
  await reviewGate.getByRole('button',{name:'Request changes',exact:true}).click()
  await reviewGate.waitFor({state:'detached'})
  assert((await calls()).some(call=>call.command==='review'&&call.args.accept===false))
  await page.evaluate(()=>window.__setRunState('review'))
  await button('Refresh Work').click()
  await reviewGate.waitFor()
  await reviewGate.getByLabel('Review notes for Plan',{exact:true}).fill('Plan checked against the request.')
  await reviewGate.getByRole('button',{name:'Approve step',exact:true}).click()
  await reviewGate.waitFor({state:'detached'})
  assert((await calls()).some(call=>call.command==='review'&&call.args.accept===true))

  await button('Close').click()
  await button('Workflows').click()
  await page.getByRole('heading',{name:'Reusable workflows',exact:true}).waitFor()
  await page.locator('.wh-workflow-card').filter({hasText:'Deliver a feature'}).getByRole('button',{name:'Edit workflow'}).click()
  await page.getByRole('region',{name:'Visual workflow builder'}).waitFor()
  await page.screenshot({path:'test-results/work-redesign/builder.png',fullPage:true})
  await page.getByLabel('Step name',{exact:true}).fill('Plan the change')
  await page.getByLabel('Step instructions',{exact:true}).fill('Inspect the request and record acceptance criteria.')
  await button('Add step').click()
  await page.getByLabel('Step name',{exact:true}).fill('Temporary step')
  await button('Remove step').click()
  await page.getByLabel('Step name',{exact:true}).waitFor()
  await page.getByLabel('Workflow title').fill('Deliver a feature v2')
  await button('Save workflow').click()
  await page.getByRole('heading',{name:'Deliver a feature v2',exact:true}).waitFor()
  const snapshot=await page.evaluate(()=>window.__workFlows())
  assert(snapshot.filter(([key])=>key.includes(':work-run-')).every(([,value])=>!value.definition.title.includes('v2')),'template edit preserves instances')
  await button('Work Items').click()
  await page.evaluate(()=>window.__setRunState('done'))
  await button('Refresh Work').click()
  await page.getByRole('heading',{name:'Verify the delivery lifecycle'}).click()
  await page.getByRole('region',{name:'Work item details'}).getByText('working',{exact:true}).waitFor()
  await button('Edit work item').click()
  await page.getByLabel('Work item state',{exact:true}).selectOption('completed')
  await button('Save work item').click()
  await page.getByRole('region',{name:'Work item details'}).getByText('completed',{exact:true}).waitFor()
  assert.equal(errors.length,0,errors.join('\n'))
  await button('Close').click()
  await page.setViewportSize({width:480,height:900})
  await page.screenshot({path:'test-results/work-redesign/board-narrow.png',fullPage:true})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'board scroll stays inside its pane')
  console.log('PASS: existing history, GitHub intake, new work item, two attached snapshots, no auto execution, completion gate, live progress, builder isolation and narrow board')
} finally {await browser.close()}
