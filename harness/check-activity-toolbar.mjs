import assert from 'node:assert/strict'
import fs from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
const base = process.env.HARNESS_URL || 'http://127.0.0.1:5199'
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
  await page.goto(`${base}/harness/visibility.html?sessions`)
  await page.getByRole('heading',{name:'Runs',exact:true}).waitFor()
  const search=await page.getByLabel('Search activity').boundingBox(),project=await page.getByLabel('Project filter',{exact:true}).boundingBox();assert(search.x<project.x)
  await page.getByLabel('Search activity').fill('Review onboarding')
  await page.getByRole('button',{name:/Review onboarding/}).waitFor()
  assert.equal(await page.getByRole('button',{name:/Build visibility/}).count(),0)
  await page.getByRole('button',{name:'Clear all filters',exact:true}).click()
  await page.getByRole('button',{name:'Done',exact:true}).click();assert(await page.getByLabel('Show done').isChecked());await page.getByLabel('Show done').uncheck()
  assert.equal(await page.getByRole('tab',{name:'GitHub issues',exact:true}).count(),0)
  fs.mkdirSync('.artifacts/visibility',{recursive:true})
  await page.goto(`${base}/harness/visibility.html?summary`)
  await page.getByRole('button', { name: 'Show 2 PRs in linked work', exact: true }).click()
  await page.getByRole('button', { name: 'devdeck #16', exact: true }).waitFor()
  await page.getByRole('button', { name: 'devdeck #19', exact: true }).waitFor()
  await page.getByRole('button', { name: 'devdeck · Run #123', exact: true }).waitFor()
  await page.getByLabel('Chat with manager').selectOption('orchestrator')
  await page.getByRole('button', { name: '2 actions · 1 failed', exact: true }).click()
  await page.getByText('files.read · Succeeded', { exact: true }).waitFor()
  await page.getByText('tests.run · Failed', { exact: true }).waitFor()
  await page.screenshot({ path: '.artifacts/visibility/timeline-clean.png' })
  await page.goto(`${base}/harness/visibility.html?slow-inbox`)
  // Preserve the strict slow-inbox isolation check against checkpoint enrichment.
  await page.getByText('GitHub checkpoint retained',{exact:true}).waitFor({timeout:5000})
  await page.getByRole('button', { name: 'Refresh', exact: true }).waitFor({ timeout: 25000 })
  await page.getByRole('alert').filter({hasText:/Could not read all local messages/}).waitFor()
  await page.goto(`${base}/harness/visibility.html?no-repositories`)
  await page.getByRole('button', { name: 'Product links', exact: true }).click()
  await page.getByRole('heading', { name: 'Product connections', exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: search, status buttons, clear filters, retained references/actions, slow inbox isolation, timeout recovery, unconnected repository guidance.')
} finally { await browser.close() }
