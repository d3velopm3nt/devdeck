import assert from 'node:assert/strict'
import fs from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
const base = process.env.HARNESS_URL || 'http://127.0.0.1:5199'
const errors = []
page.on('pageerror', e => errors.push(String(e)))
const calls = () => page.evaluate(() => window.__cliSetupCalls)
try {
  await page.goto(`${base}/harness/cli-setup.html`)
  const claude = page.getByRole('article', { name: 'Claude subscription' })
  await claude.getByText('Not installed', { exact: true }).waitFor()
  assert.equal(await claude.getByRole('button', { name: 'Sign in with Claude' }).count(), 0)
  await claude.getByRole('button', { name: 'Install Claude Code' }).click()
  await claude.getByText('Installation verified. You can now sign in.').waitFor()
  assert.equal((await calls()).find(c => c.command === 'plan').args.action, 'install')
  await claude.getByRole('button', { name: 'Sign in with Claude' }).click()
  await claude.getByText('Subscription sign-in verified.').waitFor()
  assert.equal((await calls()).filter(c => c.command === 'terminal').length, 2)
  assert.equal((await calls()).filter(c => c.command === 'plan')[1].args.action, 'sign-in')
  console.log('PASS: install and subscription login verified only after CLI status changes')
  await page.goto(`${base}/harness/cli-setup.html?scenario=api`)
  await page.getByText('API billing active', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Sign in with ChatGPT' }).waitFor()
  assert.equal(await page.getByText('Subscription signed in', { exact: true }).count(), 0)
  console.log('PASS: API billing is not presented as subscription access')
  await page.goto(`${base}/harness/cli-setup.html?scenario=failure`)
  await page.getByRole('button', { name: 'Install Codex CLI' }).click()
  await page.getByRole('alert').getByText(/Fixture CLI installer unavailable/).waitFor()
  assert.equal((await calls()).filter(c => c.command === 'terminal').length, 0)
  assert.equal(await page.getByRole('button', { name: 'Install Codex CLI' }).isEnabled(), true)
  console.log('PASS: failed setup remains retryable and creates no terminal')
  await page.goto(`${base}/harness/cli-setup.html?scenario=unfinished`)
  const codex = page.getByRole('article', { name: 'ChatGPT subscription' })
  await codex.getByRole('button', { name: 'Install Codex CLI' }).click()
  await codex.getByRole('button', { name: 'Stop monitoring' }).click()
  await codex.getByRole('status').getByText(/terminal remains open/).waitFor()
  assert.equal(await codex.getByText('Not installed', { exact: true }).count(), 1)
  assert.equal((await calls()).filter(c => c.command === 'plan').length, 1)
  console.log('PASS: stopping monitoring does not claim cancellation or installation success')
  await page.goto(`${base}/harness/cli-setup.html?scenario=unsupported`)
  await page.getByText('In-app setup currently supports Windows.').first().waitFor()
  assert.equal(await page.getByRole('button', { name: 'Install Codex CLI' }).isDisabled(), true)
  console.log('PASS: unsupported platforms cannot start Windows installers')
  for (const scenario of ['core', 'settings']) {
    await page.goto(`${base}/harness/cli-setup.html?scenario=${scenario}`)
    await page.getByText(/No assistant provider is connected yet/).waitFor()
    const select = page.getByLabel('Default provider', { exact: true })
    assert.ok(await select.locator('option').count() > 2)
    assert.equal(await page.getByRole('button', { name: 'Verify & use as default' }).isDisabled(), true)
    await page.getByPlaceholder('sk-…', { exact: true }).fill('fixture-not-a-secret')
    await page.getByRole('button', { name: 'Connect', exact: true }).click()
    await page.waitForFunction(() => !!document.querySelector('select[aria-label="Default provider"] option[value="openrouter"]:not(:disabled)'))
    await select.selectOption('openrouter')
    await page.getByRole('button', { name: 'Verify & use as default' }).waitFor()
    assert.equal((await calls()).filter(c => c.command === 'configure-provider').length, 1)
    for (const width of [540, 900, 1280]) {
      await page.setViewportSize({ width, height: 1000 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `${scenario} overflow at ${width}px`)
    }
    console.log(`PASS: ${scenario} provider setup refreshes default choices without reload, no overflow at 540/900/1280px`)
  }
  for (const provider of ['claude-subscription', 'chatgpt-subscription']) {
    await page.goto(`${base}/harness/cli-setup.html?scenario=settings`)
    const name = provider === 'claude-subscription' ? 'Claude' : 'ChatGPT'
    const card = page.getByRole('article', { name: `${name} subscription` })
    await card.getByRole('button', { name: /Install/ }).click()
    await card.getByText('Installation verified. You can now sign in.').waitFor()
    await card.getByRole('button', { name: `Sign in with ${name}` }).click()
    await card.getByText('Subscription sign-in verified.').waitFor()
    const select = page.getByLabel('Default provider', { exact: true })
    await select.selectOption(provider)
    await page.getByRole('button', { name: 'Verify & use as default' }).waitFor()
    await page.waitForFunction(() => !!document.querySelector('button.btn-primary:not(:disabled)'))
    // The fixture's only model is selected through the production picker.
    const models = page.locator('section').filter({ hasText: 'Default assistant provider' }).locator('select').nth(1)
    await models.selectOption('fixture-model')
    await page.getByRole('button', { name: 'Verify & use as default' }).click()
    await page.getByText(/Verified and saved/).waitFor()
    assert.equal((await calls()).find(c => c.command === 'default-provider').args.provider, provider)
    assert.equal((await calls()).find(c => c.command === 'model-check').args.providerId, provider)
    console.log(`PASS: ${name} subscription sign-in refreshes and verifies the default without restart`)
  }
  await page.setViewportSize({ width: 1280, height: 1000 })
  await page.goto(`${base}/harness/cli-setup.html`)
  await page.getByText('Not installed', { exact: true }).first().waitFor()
  fs.mkdirSync('docs/screenshots/cli-setup', { recursive: true })
  await page.screenshot({ path: 'docs/screenshots/cli-setup/connections.png' })
  await page.goto(`${base}/harness/cli-setup.html?scenario=core`)
  await page.getByText(/No assistant provider is connected yet/).waitFor()
  await page.screenshot({ path: 'docs/screenshots/cli-setup/core-setup.png', fullPage: true })
  assert.deepEqual(errors, [])
} finally { await browser.close() }
