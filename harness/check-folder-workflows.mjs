import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
const base = process.env.HARNESS_URL || 'http://127.0.0.1:5199'
const button = name => page.getByRole('button', { name, exact: true })
try {
  await page.goto(`${base}/harness/folder-workflows.html`)
  await page.getByRole('heading', { name: 'Campaign', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.__workflowCalls.length), 0, 'opening a labelled folder starts nothing')
  await page.getByRole('button', { name: /STEP 2/ }).click()
  await page.getByText('Waiting for dependencies to be accepted.').waitFor()
  assert.equal(await button('Start step').count(), 0)
  await page.getByRole('button', { name: /STEP 1/ }).click()
  await button('Start workflow').click()
  assert.equal(await page.evaluate(() => window.__workflowCalls.filter(c => c.command === 'start').length), 0, 'preview starts nothing')
  await button('Start this step').click()
  await button('Stop worker').waitFor()
  assert.equal(await button('Start step').count(), 0, 'running step cannot be started again')
  await page.evaluate(() => window.__complete())
  await button('Accept step').waitFor()
  assert(await button('Accept step').isDisabled(), 'review requires evidence')
  await page.getByRole('button', { name: /STEP 2/ }).click()
  await page.getByText('Waiting for dependencies to be accepted.').waitFor()
  await page.getByRole('button', { name: /STEP 1/ }).click()
  await page.getByLabel('Review evidence').fill('Reviewed claims and saved accepted draft in campaign.md.')
  await button('Accept step').click()
  await page.getByText('1 of 2 accepted · Manual start').waitFor()
  await page.getByRole('button', { name: /STEP 2/ }).click()
  await button('Start step').waitFor()
  assert.equal(await page.evaluate(() => window.__workflowCalls.filter(c => c.command === 'start').length), 1, 'acceptance does not silently start another worker')
  console.log('PASS: manual preview/start, live event update, review evidence and dependency gate')

  await page.goto(`${base}/harness/folder-workflows.html`)
  await button('Edit workflow').click()
  await page.getByLabel('Workflow Markdown').fill('a locally edited draft')
  await page.evaluate(() => window.__externalEdit())
  await button('Save workflow').click()
  await page.getByRole('alert').getByText('This workflow changed. Reload before saving.').waitFor()
  assert.equal(await page.getByLabel('Workflow Markdown').inputValue(), 'a locally edited draft')
  assert.equal(await page.evaluate(() => window.__workflowCalls.find(c => c.command === 'save').args.expected), 'revision-1')
  console.log('PASS: external update cannot overwrite a stale editor draft')
  assert.deepEqual(errors, [])
} finally { await browser.close() }
