import assert from 'node:assert/strict'
import fs from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
const base = process.env.HARNESS_URL || 'http://127.0.0.1:5199'
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
  await page.goto(`${base}/harness/visibility.html`)
  await page.getByRole('tab', { name: 'GitHub issues', exact: true }).click()
  await page.getByText(/Read succeeded · 2 items/).waitFor()
  const search = await page.getByLabel('Search activity').boundingBox()
  const project = await page.getByLabel('Project filter', { exact: true }).boundingBox()
  assert.ok(search.x < project.x, 'Search leads the toolbar')
  await page.getByRole('button', { name: 'List', exact: true }).click()
  await page.getByLabel('Search activity').fill('unclaimed')
  await page.getByRole('button', { name: /#9 Unclaimed GitHub issue/ }).waitFor()
  assert.equal(await page.getByRole('button', { name: /#8 Activity board/ }).count(), 0)
  await page.getByRole('button', { name: 'Clear all filters', exact: true }).click()
  await page.getByRole('button', { name: 'Working', exact: true }).click()
  await page.getByRole('button', { name: /#8 Activity board/ }).waitFor()
  assert.equal(await page.getByRole('button', { name: /#9 Unclaimed/ }).count(), 0)
  await page.getByRole('button', { name: 'Clear all filters', exact: true }).click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  assert.ok(await page.getByLabel('Show done').isChecked())
  await page.getByLabel('Show done').uncheck()
  await page.getByRole('button', { name: /#8 Activity board/ }).waitFor()
  fs.mkdirSync('docs/screenshots/visibility', { recursive: true })
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'light'))
  await page.screenshot({ path: 'docs/screenshots/visibility/issues-list-clean.png' })
  await page.getByRole('button', { name: 'Board', exact: true }).click()
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'))
  await page.screenshot({ path: 'docs/screenshots/visibility/issues-board-clean.png' })
  await page.goto(`${base}/harness/visibility.html?slow-inbox`)
  await page.getByRole('tab', { name: 'GitHub issues', exact: true }).click()
  await page.getByText(/Read succeeded · 2 items/).waitFor({ timeout: 5000 })
  await page.getByRole('button', { name: /#8 Activity board/ }).waitFor()
  await page.getByRole('button', { name: 'Refresh', exact: true }).waitFor({ timeout: 25000 })
  await page.getByRole('alert').getByText(/Could not read all local messages/).waitFor()
  await page.goto(`${base}/harness/visibility.html?no-repositories`)
  await page.getByRole('tab', { name: 'GitHub issues', exact: true }).click()
  await page.getByText(/No repositories connected/).waitFor()
  await page.getByRole('button', { name: 'Connect repository', exact: true }).click()
  await page.getByRole('heading', { name: 'Product connections', exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: search, status buttons, clear filters, Board/List, themes, slow inbox isolation, timeout recovery, unconnected repository guidance.')
} finally { await browser.close() }
