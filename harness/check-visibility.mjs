import assert from 'node:assert/strict'
import fs from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})})
const page = await browser.newPage({viewport:{width:1600,height:1000}})
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
const base=process.env.HARNESS_URL || 'http://127.0.0.1:5199'
try {
  await page.goto(`${base}/harness/visibility.html`)
  await page.getByRole('button',{name:/#8 Activity board/}).waitFor()
  await page.getByRole('button',{name:/Clear pool weeds/}).waitFor()
  await page.getByRole('button',{name:/#9 Unclaimed GitHub issue/}).waitFor()
  await page.getByLabel('Assistant filter').selectOption('ChatGPT')
  assert.equal(await page.getByRole('button',{name:/#9 Unclaimed/}).count(),0)
  assert.equal(await page.getByRole('button',{name:/Clear pool weeds/}).count(),0)
  await page.getByRole('button',{name:/#8 Activity board/}).click()
  await page.getByText(/Next action: Open review PR/).waitFor()
  await page.getByText('Built board and session linkage',{exact:true}).waitFor()
  await page.evaluate(()=>window.__checkpoint())
  await page.getByText(/Next action: Verify Windows CI/).waitFor()
  await page.getByText('Handoff ready for Claude',{exact:true}).waitFor()
  await page.getByLabel('Assistant filter').selectOption('')
  await page.getByLabel('Product filter').selectOption('devdeck')
  assert.equal(await page.getByRole('button',{name:/Clear pool weeds/}).count(),0)
  await page.getByLabel('Product filter').selectOption('')
  fs.mkdirSync('docs/screenshots/visibility',{recursive:true})
  await page.screenshot({path:'docs/screenshots/visibility/activity.png'})
  await page.evaluate(()=>window.__remoteFailure())
  await page.getByRole('button',{name:'Refresh',exact:true}).click()
  await page.getByRole('alert').getByText(/Repository read failed/).waitFor()
  await page.getByRole('button',{name:/Clear pool weeds/}).waitFor()
  await page.getByRole('button',{name:/#8 Activity board/}).waitFor()
  await page.getByRole('button',{name:'Product connections',exact:true}).click()
  await page.evaluate(()=>window.__externalEdit())
  await page.getByRole('button',{name:'Save connections',exact:true}).click()
  await page.getByRole('alert').getByText(/Product links changed/).waitFor()
  await page.goto(`${base}/harness/visibility.html?sessions`)
  await page.getByRole('heading',{name:'Sessions',exact:true}).waitFor()
  await page.getByRole('button',{name:/Review onboarding.*Stale/}).waitFor()
  await page.getByLabel('Session filter').selectOption('chatgpt-visibility')
  assert.equal(await page.getByRole('button',{name:/Review onboarding/}).count(),0)
  await page.getByRole('button',{name:/Build visibility/}).click()
  await page.getByText('Built board and session linkage',{exact:true}).waitFor()
  await page.screenshot({path:'docs/screenshots/visibility/sessions.png'})
  assert.deepEqual(errors,[])
  console.log('PASS: GitHub + Personal work, unclaimed issues, product/assistant/session filters, checkpoint refresh, stale sessions, error preserves work, revision guard, no page errors.')
} finally { await browser.close() }
