import assert from 'node:assert/strict'
import fs from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1000, height: 700 } })
const errors = []
page.on('pageerror', e => errors.push(String(e)))
try {
  await page.goto(`${process.env.HARNESS_URL || 'http://127.0.0.1:5199'}/harness/space-switcher.html`)
  const trigger = () => page.getByRole('button', { name: /^Switch space:/ })
  const dialog = page.getByRole('dialog', { name: 'Switch space' })
  await trigger().click()
  await page.getByRole('textbox', { name: 'Search spaces' }).fill('inno')
  assert.equal(await dialog.getByRole('button').count(), 1)
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await page.getByRole('status').getByText('Selected: 2', { exact: true }).waitFor()
  assert.equal(await dialog.count(), 0)
  assert.equal(await trigger().evaluate(e => e === document.activeElement), true)
  await trigger().press('ArrowDown')
  assert.equal(await dialog.getByRole('button', { name: /InnoTrack/ }).getAttribute('aria-pressed'), 'true')
  await page.keyboard.press('Escape')
  assert.equal(await dialog.count(), 0)
  await trigger().click()
  await page.getByRole('textbox').fill('missing')
  await dialog.getByText(/No spaces match/).waitFor()
  await page.getByRole('button', { name: 'Toggle sidebar' }).click()
  assert.equal(await dialog.count(), 0)
  await trigger().click()
  await dialog.getByRole('button', { name: /All spaces/ }).click()
  await page.getByRole('status').getByText('Selected: all', { exact: true }).waitFor()
  console.log('PASS: search, keyboard selection, scope reset, Escape and outside dismissal, focus restored')
  fs.mkdirSync('docs/screenshots/space-switcher', { recursive: true })
  await page.getByRole('button', { name: 'Toggle sidebar' }).click()
  for (const theme of ['dark', 'light']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
    await trigger().click()
    await dialog.waitFor()
    await page.screenshot({ path: `docs/screenshots/space-switcher/${theme}.png` })
    await page.keyboard.press('Escape')
  }
  for (const width of [320, 540, 1000]) {
    await page.setViewportSize({ width, height: 500 })
    await trigger().click()
    const bounds = await dialog.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y >= 0 && bounds.y + bounds.height <= 500)
    assert.equal(await dialog.evaluate(e => e.scrollWidth <= e.clientWidth), true)
    await page.getByRole('textbox').press('ArrowUp')
    await page.keyboard.press('Enter')
    await page.getByRole('status').getByText('Selected: 25', { exact: true }).waitFor()
  }
  assert.deepEqual(errors, [])
  console.log('PASS: both themes, narrow windows, long names and scrolling through many spaces')
} finally { await browser.close() }
