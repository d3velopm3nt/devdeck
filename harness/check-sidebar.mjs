import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true })
const page = await browser.newPage({ viewport: { width: 1100, height: 700 } })
try {
  await page.goto('http://localhost:5199/harness/index.html?view=team')
  await page.waitForFunction(() => document.documentElement.dataset.ready === '1')
  await page.evaluate(() => { window.__app.getState().setBottomTab('schedules'); window.__app.getState().setBottomCollapsed(false) })
  const nav = page.getByRole('navigation', { name: 'Primary navigation' })
  await nav.getByRole('button', { name: 'Tools', exact: true }).click()
  assert.ok(await nav.locator('.app-rail-scroll').evaluate(el => el.scrollHeight > el.clientHeight))
  await nav.getByRole('button', { name: 'Settings', exact: true }).scrollIntoViewIfNeeded()
  const bounds = await nav.boundingBox()
  const settings = await nav.getByRole('button', { name: 'Settings', exact: true }).boundingBox()
  assert.ok(settings.y + settings.height <= bounds.y + bounds.height)
  const handle = nav.getByRole('separator')
  const h = await handle.boundingBox()
  await page.mouse.move(h.x + h.width / 2, h.y + 40)
  await page.mouse.down(); await page.mouse.move(bounds.x + 290, h.y + 40); await page.mouse.up()
  assert.equal(Math.round((await nav.boundingBox()).width), 290)
  await handle.press('ArrowLeft')
  assert.equal(await handle.getAttribute('aria-valuenow'), '282')
  await nav.getByRole('button', { name: 'Collapse the navigation' }).click()
  assert.equal((await nav.boundingBox()).width, 52)
  await nav.getByRole('button', { name: 'Expand the navigation' }).click()
  assert.equal((await nav.boundingBox()).width, 282)
  await page.reload(); await nav.waitFor()
  assert.equal((await nav.boundingBox()).width, 282)
  await handle.press('Home'); assert.equal(await handle.getAttribute('aria-valuenow'), '168')
  await handle.press('End'); assert.equal(await handle.getAttribute('aria-valuenow'), '360')
  await page.setViewportSize({width:620,height:570})
  await page.waitForFunction(() => document.querySelector('.rail-resizer').getAttribute('aria-valuemax') === '248')
  assert.equal((await nav.boundingBox()).width,248)
  await page.evaluate(() => { window.__app.getState().setBottomTab('schedules'); window.__app.getState().setBottomCollapsed(false) })
  await nav.getByRole('button', { name: 'Settings', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({path:'test-results/sidebar-short.png'})
  await handle.dblclick(); assert.equal(await handle.getAttribute('aria-valuenow'),'188')
  console.log('PASS: short sidebar scroll, expanded tools, drag, keyboard limits, collapse, persistence, responsive width and reset')
} finally { await browser.close() }
