import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const out='docs/test-reports/workforce-2026-10-16';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:5199/harness/workforce.html');
 await page.evaluate(async()=>{
  const {SEED}=await import('/harness/seed.ts');
  const originalWorkers=SEED.workers_list;
  const originalTeams=SEED.reusable_teams_list;
  window.createdAgents=[];window.createdTeams=[];window.createAttempts=0;window.failCreate=true;
  SEED.workers_list=()=>[...originalWorkers(),...window.createdAgents];
  SEED.reusable_teams_list=()=>[...originalTeams(),...window.createdTeams];
  SEED.library_agents=()=>window.createdAgents.map(w=>({id:`worker:${w.handle}`,name:w.name,instructions:w.body,skills:[],execution:'cli',configuration:{handle:w.handle}}));
  SEED.aiw_team_planner_send=()=>({reply:JSON.stringify({message:'Here is a compact development team. The lead coordinates delivery, engineering implements, and QA reviews independently.',choices:[],proposal:{name:'Product delivery team',description:'Build and maintain a small software product with independent review.',members:[{role:'lead',name:'Delivery lead',kind:'manager',reports_to:'',instructions:'Plan milestones, coordinate handoffs, and report blockers.'},{role:'engineer',name:'Product engineer',kind:'specialist',reports_to:'lead',instructions:'Implement scoped changes and provide test evidence.'},{role:'qa',name:'Quality reviewer',kind:'specialist',reports_to:'lead',instructions:'Review correctness, accessibility, and regression risks.'}]}})});
  SEED.team_builder_create=({proposal})=>{
   window.createAttempts++; if(window.failCreate)throw new Error('Temporary save failure. Retry the same proposal.');
   const previous=window.createdTeams.find(t=>t.id===proposal.id);if(previous)return previous;
   const template=originalWorkers()[0];
   const roles=proposal.members.map(m=>{const handle=m.worker||`${proposal.id}-${m.role}`;if(!m.worker)window.createdAgents.push({...template,handle,name:m.name,body:m.instructions});return {name:m.role,worker:handle,kind:m.kind,reports_to:m.reports_to,instructions:m.worker?m.instructions:'',handoffs:[]}});
   const team={id:proposal.id,name:proposal.name,description:proposal.description,roles,revision:1};window.createdTeams.push(team);return team;
  };
 });
 const parserChecks=await page.evaluate(async()=>{
  const {parsePlannerReply}=await import('/src/components/agents/TeamBuild.tsx');
  const invalid=parsePlannerReply(JSON.stringify({message:'Broken hierarchy',proposal:{name:'Invalid',members:[{role:'lead',name:'Lead',kind:'manager',reports_to:'lead',instructions:'Plan'}]}}));
  return {rejected:!invalid.proposal,explained:!!invalid.proposalIssue};
 });
 assert.deepEqual(parserChecks,{rejected:true,explained:true});
 await page.getByRole('navigation',{name:'Workforce sections'}).getByRole('button',{name:/^Build/}).click();
 await page.getByLabel('What should this team do?',{exact:true}).fill('Build a small software product with independent quality review.');
 await page.getByRole('button',{name:'Discuss my team',exact:true}).click();
 const review=page.getByRole('region',{name:'Review team proposal'});
 await review.waitFor();
 await page.getByLabel('Agent for qa',{exact:true}).selectOption('agent-3');
 await page.setViewportSize({width:1440,height:1800});
 await page.screenshot({path:`${out}/01-proposal-desktop.png`,fullPage:true,animations:'disabled'});
 await page.setViewportSize({width:1440,height:1100});
 await page.getByRole('button',{name:'Create team',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'Temporary save failure'}).waitFor();
 assert.equal(await page.evaluate(()=>window.createdAgents.length),0);
 await page.screenshot({path:`${out}/02-retry.png`,fullPage:true,animations:'disabled'});
 await page.evaluate(()=>window.failCreate=false);
 await page.getByRole('button',{name:'Create team',exact:true}).click();
 await page.getByRole('button',{name:'Back to teams',exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>window.createdTeams.length),1);
 assert.equal(await page.evaluate(()=>window.createdAgents.length),2);
 assert.equal(await page.evaluate(()=>window.createdTeams[0].roles[2].worker),'agent-3');
 await page.screenshot({path:`${out}/03-created-designer.png`,fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Library Agents & skills',exact:true}).click();
 await page.getByRole('heading',{name:'Delivery lead',exact:true}).waitFor();
 await page.getByRole('article').filter({hasText:'Personal agent'}).getByRole('heading',{name:'Product engineer',exact:true}).waitFor();
 await page.screenshot({path:`${out}/04-library-agents.png`,fullPage:true,animations:'disabled'});
 await page.getByRole('navigation',{name:'Workforce sections'}).getByRole('button',{name:/^Build/}).click();
 await page.getByRole('button',{name:'Open saved team',exact:true}).waitFor();
 await page.setViewportSize({width:700,height:1800});
 await page.screenshot({path:`${out}/05-proposal-narrow.png`,fullPage:true,animations:'disabled'});
 await page.reload();
 await page.getByRole('navigation',{name:'Workforce sections'}).getByRole('button',{name:/^Build/}).click();
 await page.getByRole('button',{name:'Open saved team',exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Create team',exact:true}).count(),0);
 await page.setViewportSize({width:1440,height:1100});
 await page.evaluate(()=>document.documentElement.setAttribute('data-theme','light'));
 await page.mouse.move(0,0);
 await page.screenshot({path:`${out}/06-restored-discussion.png`,fullPage:true,animations:'disabled'});
 assert.deepEqual(errors,[]);
 console.log('PASS: proposal, hierarchy preview, agent reuse, failed save/retry, designer handoff, Library refresh, and saved discussion reload. Screenshots saved.');
} finally {await browser.close();}
