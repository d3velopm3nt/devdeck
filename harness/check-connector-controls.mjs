import assert from 'node:assert/strict'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH})
const page=await browser.newPage({viewport:{width:1338,height:992}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
try {
 await page.goto((process.env.HARNESS_URL||'http://127.0.0.1:5217')+'/harness/connectors.html')
 await page.getByRole('button',{name:'Manage Anthropic',exact:true}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByRole('button',{name:'Pause use',exact:true}).click()
 await dialog.locator('.connector-status').getByText('Paused',{exact:true}).waitFor()
 await dialog.getByRole('button',{name:'Resume use',exact:true}).click()
 await dialog.getByLabel('Restrict agents',{exact:true}).check()
 await dialog.getByLabel('agents exact identifiers').fill('fixture-agent,second-agent')
 await dialog.getByLabel('Restrict projects',{exact:true}).check()
 await dialog.getByLabel('projects exact identifiers').fill('trusted-project')
 await dialog.getByRole('button',{name:'Save restrictions',exact:true}).click()
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('connector-controls'))[0].projects?.[0]==='trusted-project')
 await dialog.getByRole('button',{name:'Disconnect DevDeck use',exact:true}).click()
 await dialog.locator('.connector-status').getByText('Disconnected',{exact:true}).waitFor()
 await dialog.getByRole('button',{name:'Resume use',exact:true}).click()
 assert.equal(await dialog.getByLabel('agents exact identifiers').inputValue(),'fixture-agent,second-agent')
 assert.equal(await dialog.getByLabel('projects exact identifiers').inputValue(),'trusted-project')
 await dialog.getByRole('button',{name:'Test existing owner',exact:true}).click()
 await dialog.getByText(/Fixture owner health only/).waitFor()
 await dialog.getByText('Known dependencies (1)',{exact:true}).click()
 await dialog.getByText(/Fixture direct saved mappings only/).waitFor()
 await page.screenshot({path:'.artifacts/connectors-visual/06-shared-controls.png'})
 await page.getByRole('button',{name:'Close connector details'}).click()
 await page.reload();await page.getByRole('button',{name:'Manage Anthropic',exact:true}).click()
 assert.equal(await page.getByLabel('agents exact identifiers').inputValue(),'fixture-agent,second-agent')
 await page.evaluate(()=>{const rows=JSON.parse(localStorage.getItem('connector-controls'));rows[0].revision++;localStorage.setItem('connector-controls',JSON.stringify(rows))})
 await page.getByRole('button',{name:'Save restrictions',exact:true}).click()
 await page.getByRole('alert').filter({hasText:'Connector changed'}).waitFor()
 await page.getByRole('button',{name:'Refresh controls',exact:true}).click()
 await page.getByRole('alert').filter({hasText:'Connector changed'}).waitFor({state:'detached'})
 await page.setViewportSize({width:390,height:844})
 assert(await page.getByRole('dialog').evaluate(e=>e.scrollWidth<=e.clientWidth))
 await page.screenshot({path:'.artifacts/connectors-visual/07-shared-controls-narrow.png'})
 assert.deepEqual(errors,[])
 console.log('PASS: fixture lifecycle, persisted restrictions, reconnect preservation, owner check, dependency coverage, reopen, no runtime errors')
}finally{await browser.close()}
