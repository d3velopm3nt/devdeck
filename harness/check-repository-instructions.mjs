import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1100, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
const button = name => page.getByRole('button', { name, exact: true })
const calls = () => page.evaluate(() => window.__instructionCalls)
try {
  await page.goto(`${process.env.HARNESS_URL || 'http://127.0.0.1:5202'}/harness/repository-instructions.html`)
  await page.getByRole('heading', { name: 'Build from AGENTS.md' }).waitFor()
  assert.equal((await calls()).length, 0)
  await button('Review workflow').click()
  assert.equal(await page.getByLabel(/^Step \d+ title$/).count(), 4)
  assert(await button('Save reviewed workflow').isDisabled())
  await page.getByLabel('Move step 4 up', { exact: true }).click()
  assert.equal(await page.getByLabel('Step 3 title', { exact: true }).inputValue(), 'Ship')
  await page.getByLabel('Remove step 3', { exact: true }).click()
  assert.equal(await page.getByLabel(/^Step \d+ title$/).count(), 3)
  await button('Reset suggested steps').click()
  assert.equal(await page.getByLabel(/^Step \d+ title$/).count(), 4)
  await page.getByLabel('Remove step 4', { exact: true }).click()
  await button('Create agent').click()
  assert(await button('Create in Library').isDisabled())
  await button('Import 7 selected skills').click()
  await button('Create in Library').click()
  await page.getByText('author · Repository agent is in your Library.', { exact: true }).waitFor()
  const created = (await calls()).find(c => c.command === 'agent').args.worker
  assert.equal(created.handle, '')
  assert.equal(created.skills.length, 7)
  assert.equal(created.unattended, false)
  assert.deepEqual(created.allow, [])
  assert(created.body.includes('Apply only the parts relevant'))
  await button('Review its workflow').click()
  await page.getByLabel('Workflow target folder').selectOption('42')
  await page.getByLabel('Imported workflow ID').fill('existing')
  await page.getByLabel('I reviewed the steps, conditions, agent and target folder.').check()
  await button('Save reviewed workflow').click()
  await page.getByRole('alert').filter({ hasText: 'This workflow changed' }).waitFor()
  await page.getByLabel('Imported workflow ID').fill('reviewed-workflow')
  assert(await button('Save reviewed workflow').isDisabled(), 'changing a reviewed field resets review')
  await page.getByLabel('I reviewed the steps, conditions, agent and target folder.').check()
  await page.screenshot({ path: 'test-results/team-package-import/repository-workflow-review.png', fullPage: true })
  await button('Save reviewed workflow').click()
  await page.getByText('Workflow saved. No steps started.').waitFor()
  const last = (await calls()).filter(c => c.command === 'workflow').at(-1).args
  assert.equal(last.expected, '')
  const definition = JSON.parse(last.raw.split('\n---\n')[0].slice(4))
  assert.deepEqual(definition.steps.map(s => s.title), ['Isolate', 'Build', 'Prove'])
  assert.deepEqual(definition.steps.map(s => s.needs), [[], ['step-1'], ['step-2']])
  assert.equal(errors.length, 0, errors.join('\n'))
  assert((await calls()).every(c => ['import', 'agent', 'workflow'].includes(c.command)), 'no run/start calls')
  await page.evaluate(() => window.__remountInstructions())
  await button('Create agent').click()
  await page.getByText('author · Repository agent is in your Library.', { exact: true }).waitFor()
  assert.equal(await button('Create in Library').count(), 0, 'reopening the same document offers the saved agent')
  assert.equal((await calls()).filter(c => c.command === 'agent').length, 1, 'same source revision does not create a duplicate')
  await page.setViewportSize({ width: 480, height: 900 })
  await page.reload()
  await button('Create agent').click()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'no horizontal overflow on narrow layouts')
  await page.screenshot({ path: 'test-results/team-package-import/repository-agent-import.png', fullPage: true })
  // A stale skill disappearing after preview must block agent creation.
  await button('Import 7 selected skills').click()
  await page.evaluate(() => window.__removeSkill())
  await button('Create in Library').click()
  await page.getByRole('alert').filter({ hasText: 'Install the selected skills' }).waitFor()
  assert.equal((await calls()).filter(c => c.command === 'agent').length, 0)
  console.log('PASS: reviewed extraction, skill import, collision-safe agent creation, workflow save conflict, provenance, no execution, stale dependency check and narrow layout')
} finally { await browser.close() }
