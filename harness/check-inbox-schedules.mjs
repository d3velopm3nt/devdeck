import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true })
const report = 'docs/test-reports/inbox-schedules-2026-10-17'
const results = []
const screenshots = []
let currentPage
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  currentPage = page
  page.setDefaultTimeout(60000)
  page.setDefaultNavigationTimeout(90000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://localhost:5199/harness/inbox-schedules.html')
  const inbox = page.getByRole('region', { name: 'Dev requests', exact: true })
  const request = inbox.locator('article').filter({ hasText: 'Choose a workflow for documentation' })
  await request.waitFor()
  await request.getByRole('button', { name: 'Mark read', exact: true }).click()
  await request.getByRole('button', { name: 'Mark unread', exact: true }).waitFor()
  assert.equal((await page.evaluate(() => window.fixtureRequests()))[0].status, 'needs-you')
  await page.reload()
  await request.getByRole('button', { name: 'Mark unread', exact: true }).waitFor()
  assert.equal(await request.getByRole('button', { name: 'Record resolution' }).count(), 1)
  results.push('Inbox read state reloads independently; pending request remains actionable (fixture persistence)')
  await request.getByRole('button', { name: 'Record resolution' }).click()
  assert.equal(await request.getByRole('button', { name: 'Save resolution' }).isDisabled(), true)
  await request.getByLabel('Decision or confirmed outcome').fill('Approved documentation scope in source workflow.')
  await page.evaluate(() => window.fixtureRequestVersion())
  await request.getByRole('button', { name: 'Save resolution' }).click()
  await inbox.getByRole('alert').filter({ hasText: 'This request changed' }).waitFor()
  assert.equal((await page.evaluate(() => window.fixtureRequests()))[0].status, 'needs-you')
  results.push('Stale response remains visible and pending when IPC rejects version')
  await inbox.getByRole('button', { name: 'Refresh Dev requests' }).click()
  await request.getByRole('button', { name: 'Save resolution' }).click()
  await inbox.getByRole('button', { name: 'Resolved · 1', exact: true }).click()
  await inbox.getByText('Outcome: Approved documentation scope in source workflow.').waitFor()
  await page.reload()
  await inbox.getByRole('button', { name: 'Resolved · 1', exact: true }).click()
  await inbox.getByText('Outcome: Approved documentation scope in source workflow.').waitFor()
  assert.equal(await inbox.getByRole('button', { name: 'Record resolution' }).count(), 0)
  results.push('Resolution requires outcome, moves to Resolved and reloads; resolved request cannot be reapplied in UI')
  await inbox.getByRole('button', { name: 'Needs you · 1', exact: true }).click()
  await inbox.getByRole('heading', { name: 'Review documentation changes' }).waitFor()
  results.push('Review-ready request remains pending until explicit resolution')
  await page.evaluate(() => window.fixtureRequestError(true))
  await inbox.getByRole('button', { name: 'Refresh Dev requests' }).click()
  await inbox.getByRole('alert').filter({ hasText: 'Fixture Inbox unavailable' }).waitFor()
  await page.evaluate(() => window.fixtureRequestError(false))
  await inbox.getByRole('button', { name: 'Refresh Dev requests' }).click()
  await page.waitForFunction(() => !document.querySelector('[aria-label="Dev requests"] [role="alert"]'))
  results.push('Inbox load error is visible and retry refresh recovers')
  const panel = page.getByRole('region', { name: 'Schedules', exact: true })
  await panel.getByText('Repository health check', { exact: true }).waitFor()
  const health = panel.getByRole('row').filter({ hasText: 'Repository health check' })
  const paused = panel.getByRole('row').filter({ hasText: 'Release review reminder' })
  const running = panel.getByRole('row').filter({ hasText: 'Dev repository assessment' })
  assert.equal(await health.getByRole('cell', { name: 'Enabled', exact: true }).count(), 1)
  assert.equal(await paused.getByRole('cell', { name: 'Paused', exact: true }).count(), 1)
  assert.equal(await running.getByRole('cell', { name: 'Running', exact: true }).count(), 1)
  results.push('Schedule fixture: enabled is not running, paused is explicit, running requires backend flag')
  await mkdir(report, { recursive: true })
  screenshots.push(['inbox-schedules.png', await page.screenshot()])
  await page.evaluate(() => window.fixtureSchedules('error'))
  await panel.getByRole('button', { name: 'Refresh schedules' }).click()
  await panel.getByRole('alert').waitFor()
  assert.equal(await panel.getByRole('cell', { name: 'Running', exact: true }).count(), 0)
  screenshots.push(['schedule-error.png', await page.screenshot()])
  results.push('Schedule refresh failure retains visible snapshot and suppresses stale Running claim')
  await page.evaluate(() => { window.fixtureSchedules('normal'); window.fixtureScheduleComplete() })
  await panel.getByRole('button', { name: 'Refresh schedules' }).click()
  await running.getByRole('cell', { name: 'Enabled', exact: true }).waitFor()
  results.push('Schedule completion clears Running on refresh')
  await page.evaluate(() => window.fixtureSchedules('empty'))
  await panel.getByRole('button', { name: 'Refresh schedules' }).click()
  await panel.getByText('No schedules yet', { exact: true }).waitFor()
  results.push('Empty schedule state is actionable')
  await panel.getByRole('button', { name: 'Manage schedules' }).click()
  await page.waitForFunction(() => window.fixtureAppState().railView === 'settings')
  assert.deepEqual(await page.evaluate(() => { const s = window.fixtureAppState(); return [s.railView, s.settingsTab] }), ['settings', 'routines'])
  results.push('Manage schedules opens Settings / routines')
  await page.evaluate(() => window.fixtureSchedules('normal'))
  await panel.getByRole('button', { name: 'Refresh schedules' }).click()
  await health.waitFor()
  await page.setViewportSize({ width: 700, height: 900 })
  screenshots.push(['narrow.png', await page.screenshot()])
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Document horizontal overflow')
  results.push('700px layout does not overflow document; schedule table scrolls internally')
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('http://localhost:5199/harness/inbox-schedules.html?today')
  const briefing = page.getByRole('region', { name: 'Dev’s briefing', exact: true })
  const avatar = page.locator('img[src="/avatars/dev-robot-v1.png"]')
  await avatar.first().waitFor()
  await page.waitForFunction(() => Array.from(document.querySelectorAll('img[src="/avatars/dev-robot-v1.png"]')).every(i => i.complete && i.naturalWidth > 0))
  await briefing.getByRole('button', { name: 'Read briefing' }).click()
  assert.equal(await briefing.getByRole('button', { name: 'Collapse', exact: true }).getAttribute('aria-expanded'), 'true')
  await briefing.getByRole('button', { name: 'Collapse', exact: true }).click()
  assert.equal(await briefing.getByRole('button', { name: 'Read briefing' }).getAttribute('aria-expanded'), 'false')
  await briefing.getByRole('link', { name: 'GitHub', exact: true }).click()
  assert.equal(await page.evaluate(() => window.fixtureOpenedUrl?.url), 'https://github.com/example/product')
  assert.equal(await page.locator('.today-activity-row').count(), 12)
  assert.equal(await page.locator('.today-activity-scroll').evaluate(el => el.scrollHeight > el.clientHeight), true)
  await page.locator('.today-activity-scroll').evaluate(el => el.scrollTop = el.scrollHeight)
  await page.getByRole('button', { name: /Documentation task 12/ }).waitFor()
  await page.locator('.today-activity-scroll').evaluate(el => el.scrollTop = 0)
  screenshots.push(['today-avatar.png', await page.screenshot()])
  for (const [name, bytes] of screenshots) await writeFile(`${report}/${name}`, bytes)
  results.push('Today avatar loads; briefing expands/collapses; GitHub link uses source repository; all 12 activity rows retained in scrollable region')
  await page.goto('http://localhost:5199/harness/inbox-schedules.html?chat')
  await page.getByRole('heading', { name: 'Chat', exact: true }).waitFor()
  await page.waitForFunction(() => Array.from(document.querySelectorAll('img[src="/avatars/dev-robot-v1.png"]')).some(i => i.complete && i.naturalWidth > 0))
  screenshots.push(['chat-avatar.png', await page.screenshot()])
  results.push('Dev avatar renders in actual chat header with fixture conversation')
  await page.goto('http://localhost:5199/harness/notifications.html')
  await page.getByRole('button', { name: 'Notifications', exact: true }).waitFor()
  await page.evaluate(async () => { localStorage.setItem('deck.settings', JSON.stringify({notificationLevel:'all',popups:true,quiet:false})); await window.pushNotice('approval') })
  await page.locator('.notification-stack img[src="/avatars/dev-robot-v1.png"]').waitFor()
  await page.waitForFunction(() => Array.from(document.querySelectorAll('.notification-stack img')).every(i => i.complete && i.naturalWidth > 0))
  screenshots.push(['alert-avatar.png', await page.screenshot()])
  results.push('Dev avatar renders in notification overlay fixture (not native window delivery)')
  assert.deepEqual(errors, [], 'Browser page errors')
  for (const [name, bytes] of screenshots) await writeFile(`${report}/${name}`, bytes)
  await writeFile(`${report}/results.json`, JSON.stringify({ mode: 'browser fixtures; not live GitHub or native persistence', results }, null, 2))
  console.log(results.map(result => `PASS: ${result}`).join('\n'))
} catch (error) {
  console.error('Completed checks:', results)
  if (currentPage) {
    console.error('Current page:', await currentPage.locator('body').innerText().catch(() => 'Unavailable'))
    screenshots.push(['failure.png', await currentPage.screenshot().catch(() => Buffer.alloc(0))])
  }
  throw error
} finally {
  await mkdir(report, { recursive: true })
  for (const [name, bytes] of screenshots) if(bytes.length) await writeFile(`${report}/${name}`, bytes)
  await writeFile(`${report}/results.json`, JSON.stringify({ mode: 'browser fixtures; not live GitHub or native persistence', results }, null, 2))
  await browser.close()
}
