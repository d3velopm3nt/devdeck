import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
const base = process.env.HARNESS_URL || 'http://127.0.0.1:5199'
try {
  await page.goto(`${base}/harness/capability-setup.html`)
  await page.getByRole('complementary', {name:'Optional setup'}).waitFor()
  await page.getByRole('button', {name:'Not now',exact:true}).click()
  assert.equal(await page.getByRole('complementary').count(), 0)
  await page.reload()
  await page.getByRole('button', {name:'Don’t show again',exact:true}).click()
  await page.reload()
  await page.getByLabel('Default provider').first().waitFor()
  assert.equal(await page.getByRole('complementary').count(), 0)
  const setup = page.locator('section').filter({has:page.getByRole('heading',{name:'Set up your assistant'})}).first()
  await setup.getByLabel('Default provider').selectOption('chatgpt-subscription')
  await setup.locator('select').nth(1).selectOption('default')
  await setup.getByRole('button',{name:'Verify & use as default'}).click()
  await setup.getByRole('button',{name:'Start chatting'}).waitFor()
  assert.deepEqual(await page.evaluate(()=>window.__setupCalls),['verify','save'])
  await setup.getByRole('button',{name:'Start chatting'}).click()
  assert.equal(await page.evaluate(()=>window.__setupApp.getState().railView),'chat')
  await page.getByRole('button',{name:'Agents',exact:true}).click()
  assert.equal(await page.getByRole('option',{name:/scripted|mock/i}).count(),0)
  await page.goto(`${base}/harness/capability-setup.html?fail`)
  const failSetup = page.locator('section').filter({has:page.getByRole('heading',{name:'Set up your assistant'})}).first()
  await failSetup.getByLabel('Default provider').selectOption('chatgpt-subscription')
  await failSetup.locator('select').nth(1).selectOption('default')
  await failSetup.getByRole('button',{name:'Verify & use as default'}).click()
  await failSetup.getByRole('status').filter({hasText:'Verification failed'}).waitFor()
  assert.deepEqual(await page.evaluate(()=>window.__setupCalls),['verify'])
  assert.equal(await failSetup.getByRole('button',{name:'Start chatting'}).count(),0)
  assert.deepEqual(errors,[])
  console.log('PASS: dismissal persistence, subscription default selection, verify-before-save, chat handoff, no mock options, failed verification does not save')
} finally { await browser.close() }
