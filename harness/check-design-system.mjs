import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,headless:true})
const results=[]
const report='test-results/design-system'
await mkdir(report,{recursive:true})
const page=await browser.newPage({viewport:{width:1440,height:960}})
page.setDefaultTimeout(60000)
const errors=[];page.on('pageerror',e=>errors.push(e.message))
const base='http://localhost:5199/harness/'
try {
 await page.goto(base+'design-system.html')
 await page.getByRole('heading',{name:'DevDeck design system'}).waitFor()
 const tabs=page.getByRole('tablist',{name:'Gallery tabs'})
 await tabs.getByRole('tab',{name:'Overview'}).focus()
 await page.keyboard.press('ArrowRight')
 assert.equal(await tabs.getByRole('tab',{name:'Activity'}).getAttribute('aria-selected'),'true')
 await page.keyboard.press('End')
 assert.equal(await tabs.getByRole('tab',{name:'Settings'}).getAttribute('aria-selected'),'true')
 await page.keyboard.press('Home')
 assert.equal(await tabs.getByRole('tab',{name:'Overview'}).getAttribute('aria-selected'),'true')
 for(const theme of ['dark','light','claude','vercel','vercel-light','vscode']) {
  await page.evaluate(t=>document.documentElement.dataset.theme=t,theme)
  await page.screenshot({path:`${report}/states-${theme}.png`})
  const bad=await page.locator('.ds-state').evaluateAll(nodes=>{
   const canvas=document.createElement('canvas');canvas.width=canvas.height=1;const ctx=canvas.getContext('2d')
   const rgb=color=>{ctx.clearRect(0,0,1,1);ctx.fillStyle=color;ctx.fillRect(0,0,1,1);return [...ctx.getImageData(0,0,1,1).data].slice(0,3)}
   const lum=c=>c.map(v=>{v/=255;return v<=.04045?v/12.92:((v+.055)/1.055)**2.4}).reduce((s,v,i)=>s+v*[.2126,.7152,.0722][i],0)
   return nodes.map(n=>{const st=getComputedStyle(n),a=lum(rgb(st.color)),b=lum(rgb(st.backgroundColor));return {label:n.textContent,contrast:(Math.max(a,b)+.05)/(Math.min(a,b)+.05)}}).filter(x=>x.contrast<4.5)
  })
  assert.deepEqual(bad,[],theme+' badge text contrast')
 }
 results.push('Six themes: state badge contrast >=4.5:1; tabs support arrows/Home/End')
 await page.goto(base+'inbox-schedules.html')
 const requests=page.getByRole('region',{name:'Dev requests',exact:true})
 await requests.getByRole('button',{name:'Resolved',exact:true}).click()
 await requests.getByRole('button',{name:'Needs you',exact:true}).click()
 const schedules=page.getByRole('region',{name:'Schedules',exact:true})
 for(const name of ['Enabled','Running','Paused']) await schedules.getByRole('cell',{name,exact:true}).first().waitFor()
 await page.getByRole('group',{name:'Utility panels'}).getByRole('button',{name:'Processes',exact:true}).click()
 await page.getByRole('group',{name:'Utility panels'}).getByRole('button',{name:'Schedules',exact:true}).click()
 await schedules.waitFor()
 await page.screenshot({path:report+'/inbox-schedules.png'})
 results.push('Inbox filters, utility panel switching and distinct schedule states')
 await page.goto(base+'visibility.html')
 await page.getByRole('tab',{name:'GitHub issues',exact:true}).click()
 await page.getByText(/Read succeeded · 2 items/).waitFor()
 await page.getByRole('button',{name:'List',exact:true}).click()
 await page.getByRole('button',{name:'Working',exact:true}).click()
 await page.getByRole('button',{name:/#8 Activity board/}).waitFor()
 await page.screenshot({path:report+'/activity.png'})
 results.push('Activity tabs, list layout and status filtering')
 await page.goto(base+'desktop-design.html')
 await page.getByRole('heading',{name:'Today',exact:true}).waitFor()
 await page.getByRole('group',{name:'Activity source'}).getByRole('button',{name:'Mail',exact:true}).click()
 await page.locator('.today-activity').getByRole('button',{name:/3 unread messages/}).waitFor()
 await page.screenshot({path:report+'/today.png'})
 await page.getByRole('button',{name:'Notifications',exact:true}).first().click()
 await page.getByRole('heading',{name:'Notifications',exact:true}).waitFor()
 await page.screenshot({path:report+'/settings.png'})
 results.push('Today source filters and settings navigation')
 await page.goto(base+'index.html?view=mail')
 await page.getByRole('group',{name:'Mail views'}).getByRole('button',{name:'Contacts',exact:true}).click()
 await page.getByRole('group',{name:'Mail views'}).getByRole('button',{name:'Mail',exact:true}).click()
 await page.screenshot({path:report+'/mail.png'})
 results.push('Mail/Contacts switching in the app shell')
 assert.deepEqual(errors,[])
 console.log(results.map(r=>'PASS: '+r).join('\n'))
} catch(e) {await page.screenshot({path:report+'/failure.png'});throw e}
finally {await writeFile(report+'/results.json',JSON.stringify({mode:'mock IPC; no live services',results,errors},null,2));await browser.close()}
