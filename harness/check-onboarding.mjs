import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
const base = process.env.HARNESS_URL || 'http://127.0.0.1:5199'
const button = () => page.getByRole('button', { name: 'Connect state repository', exact: true })
const calls = () => page.evaluate(() => window.__onboardingCalls)
try {
  await page.goto(`${base}/harness/onboarding.html`)
  await page.getByText('GitHub sign-in is not configured in this build.', { exact: false }).waitFor()
  assert(await page.getByRole('button', { name: 'Connect with GitHub', exact: true }).isDisabled())
  await page.getByRole('button', { name: 'Use a personal access token instead' }).click()
  await page.locator('input[type=password]').fill('fixture-token-not-a-real-credential')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByText('Connected as fixture-user').waitFor()
  assert.equal(await page.locator('input[type=password]').inputValue(), '')
  await page.getByLabel('State repository', { exact: true }).selectOption('https://github.com/fixture-user/state.git')
  await button().click()
  await page.getByRole('status').getByText('State connected').waitFor()
  assert.deepEqual((await calls()).map(c => c.command), ['clone', 'select'])
  assert.equal((await calls())[1].args.path, 'C:/DevDeck/state')
  assert.equal((await calls())[1].args.gitInit, false)
  console.log('PASS: PAT fallback loads repositories and selects the cloned state')

  await page.goto(`${base}/harness/onboarding.html?scenario=retry`)
  await page.getByLabel('Repository URL', { exact: true }).fill('https://github.com/fixture-user/state.git')
  await button().click()
  await page.getByText('Fixture index failed').waitFor()
  await button().click()
  await page.getByRole('status').getByText('State connected').waitFor()
  assert.deepEqual((await calls()).map(c => c.command), ['clone', 'select', 'select'])
  console.log('PASS: retry after selection failure reuses the successful clone')

  await page.goto(`${base}/harness/onboarding.html?scenario=clone-failure`)
  await page.getByLabel('Repository URL', { exact: true }).fill('https://github.com/fixture-user/state.git')
  await button().click()
  await page.getByText('Fixture clone failed').waitFor()
  assert.deepEqual((await calls()).map(c => c.command), ['clone'])
  console.log('PASS: failed clone does not select a root or complete setup')

  await page.goto(`${base}/harness/onboarding.html`)
  await page.getByLabel('Repository URL', { exact: true }).fill('https://github.com/user:secret@evil.example/state')
  await button().click()
  await page.getByText('Choose a GitHub repository or enter its HTTPS URL.').waitFor()
  assert.equal((await calls()).length, 0)
  await page.getByRole('button', { name: 'Existing clone or local folder', exact: true }).click()
  await page.getByRole('button', { name: 'Use this state folder', exact: true }).click()
  await page.getByRole('status').getByText('State connected').waitFor()
  assert.deepEqual((await calls()).map(c => c.command), ['select'])
  console.log('PASS: invalid remote rejected; local setup works without authentication')

  await page.goto(`${base}/harness/onboarding.html?scenario=oauth`)
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent.includes('Connect with GitHub') && !b.disabled))
  await page.goto(`${base}/harness/onboarding.html?scenario=work-life`)
  await page.getByRole('button', { name: 'Add a business', exact: true }).first().waitFor()
  await page.getByRole('button', { name: 'Add a personal space', exact: true }).click()
  await page.getByRole('button', { name: 'Draft it', exact: true }).click()
  await page.getByRole('button', { name: 'See what this makes', exact: true }).click()
  assert.equal((await calls()).length, 0, 'Review must not create anything')
  await page.getByRole('button', { name: 'Create the space', exact: true }).click()
  await page.getByRole('button', { name: 'Open it', exact: true }).click()
  await page.getByRole('button', { name: 'Open Life', exact: true }).waitFor()
  const created = (await calls())[0].args
  assert.equal(created.name, 'Life')
  assert.equal(created.label, 'Personal')
  assert.deepEqual(created.folders.map(f => f.name), ['Family', 'Home', 'Finance', 'Health', 'Routines', 'Knowledge'])
  assert.equal(created.botName, 'Life manager')
  assert(created.botGoal.includes('balance'))
  assert.deepEqual(created.routines.map(r => r.at_min), [1080, 1080])
  await page.getByRole('button', { name: 'Go to Today', exact: true }).click()
  await page.getByRole('status').getByText('Setup complete').waitFor()
  console.log('PASS: Work/Life onboarding previews Life before creating its areas, manager and rhythms; existing Life reopens')
  await page.goto(`${base}/harness/onboarding.html?scenario=shared-team`)
  await page.getByRole('button', { name: 'Works for Second company too', exact: true }).waitFor()
  await page.getByText('shared manager', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Make Second company', exact: true }).click()
  await page.getByText('Second company is a space', { exact: true }).waitFor()
  assert.deepEqual((await calls())[0].args.roles, [], 'Existing role is reused without making a duplicate')
  assert.deepEqual((await calls())[0].args.reuse, ['shared-engineering'])
  console.log('PASS: second company suggests its existing functional manager and creates no duplicate')
  assert.equal(errors.length, 0, errors.join('\n'))
  console.log('PASS: configured OAuth option enabled; no browser errors')
} finally { await browser.close() }
