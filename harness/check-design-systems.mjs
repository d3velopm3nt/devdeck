const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser = await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_EXECUTABLE ? {executablePath:process.env.PLAYWRIGHT_EXECUTABLE} : {})});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
const results=[]; const passed = name => results.push({name,status:'passed'});
try {
  await page.goto('http://127.0.0.1:5199/harness/design-systems.html');
  await page.evaluate(()=>localStorage.clear()); await page.reload();
  await page.getByRole('button',{name:'Design systems',exact:true}).click();
  await page.getByRole('heading',{name:'Supabase Inspired',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Assign design',exact:true}).isDisabled(),true);
  await page.getByLabel('Search designs').fill('no-such-design');
  await page.getByText('No matching designs.',{exact:true}).waitFor();
  await page.getByLabel('Search designs').fill(''); passed('catalog, search and unselected-project guard');
  await page.getByLabel('Assign to project',{exact:true}).selectOption('1');
  await page.getByText('Saved design: None',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Assign design',exact:true}).click();
  await page.getByText('Saved design: Supabase Inspired · version 1',{exact:true}).waitFor();
  await page.screenshot({path:'test-results/design-systems/after-dark.png',fullPage:true});
  await page.getByRole('button',{name:'Light',exact:true}).click();
  assert.equal(await page.locator('.ds-specimens').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(250, 250, 250)');
  await page.screenshot({path:'test-results/design-systems/after-light.png',fullPage:true}); passed('assign and light/dark preview');
  await page.reload(); await page.getByRole('button',{name:'Design systems',exact:true}).click();
  await page.getByLabel('Assign to project',{exact:true}).selectOption('1');
  await page.getByText('Saved design: Supabase Inspired · version 1',{exact:true}).waitFor();
  await page.screenshot({path:'test-results/design-systems/after-reopen.png',fullPage:true});
  await page.getByLabel('Assign to project',{exact:true}).selectOption('2');
  await page.getByText('Saved design: None',{exact:true}).waitFor(); passed('browser-fixture reopen persistence and project isolation');
  await page.evaluate(()=>localStorage.setItem('design-fixture-fail','1'));
  await page.getByRole('button',{name:'Assign design',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Simulated disk write failure'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Assign design',exact:true}).isDisabled(),true);
  await page.evaluate(()=>localStorage.removeItem('design-fixture-fail'));
  await page.getByRole('button',{name:'Reload assignment',exact:true}).click();
  await page.getByText('Saved design: None',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Assign design',exact:true}).click();
  await page.getByText('Saved design: Supabase Inspired · version 1',{exact:true}).waitFor(); passed('failed write stays unsaved and reload recovers');
  await page.evaluate(()=>localStorage.setItem('design-fixture-2',JSON.stringify({design_id:null,version:0,revision:2})));
  await page.getByRole('button',{name:'Clear assignment',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Design selection changed'}).waitFor();
  await page.getByRole('button',{name:'Reload assignment',exact:true}).click();
  await page.getByText('Saved design: None',{exact:true}).waitFor(); passed('stale revision is visible and requires reload');
  await page.getByLabel('Assign to project',{exact:true}).selectOption('1');
  await page.getByText('Saved design: Supabase Inspired · version 1',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Clear assignment',exact:true}).click();
  await page.getByText('Saved design: None',{exact:true}).waitFor(); passed('clear selection');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
  await page.screenshot({path:'test-results/design-systems/after-mobile.png',fullPage:true}); passed('390px no horizontal overflow');
  assert.deepEqual(errors,[]);
  fs.writeFileSync('test-results/design-systems/browser-results.json',JSON.stringify({boundary:'Real React UI and typed IPC wrappers; simulated Tauri persistence via localStorage, not native Windows evidence.',results,errors},null,2)+'\n');
  console.log(JSON.stringify(results));
} finally {await browser.close();}
