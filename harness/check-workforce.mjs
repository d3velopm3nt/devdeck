const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser = await chromium.launch({headless:true, ...(process.env.PLAYWRIGHT_CHANNEL ? {channel:process.env.PLAYWRIGHT_CHANNEL} : {})});
const page = await browser.newPage({viewport:{width:1440,height:960}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
await page.goto('http://localhost:5199/harness/workforce.html');
await page.getByRole('heading',{name:'Workforce',exact:true}).waitFor();
await page.getByRole('heading',{name:'Development team',exact:true}).waitFor();
await page.getByLabel('Search teams',{exact:true}).fill('Research');
assert.equal(await page.getByRole('heading',{name:'Development team',exact:true}).count(),0);
await page.getByLabel('Search teams',{exact:true}).fill('');
await page.getByRole('button',{name:'Team table view',exact:true}).click();
assert.equal(await page.locator('table tbody tr').count(),2);
await page.getByRole('button',{name:'Solo',exact:true}).click();
assert.equal(await page.locator('table tbody tr').count(),1);
await page.getByRole('button',{name:'All teams',exact:true}).click();
await page.getByRole('button',{name:'Team card view',exact:true}).click();
fs.mkdirSync('test-results/workforce',{recursive:true});
await page.screenshot({path:'test-results/workforce/teams.png',fullPage:true});
await page.getByRole('button',{name:'Library Agents & skills',exact:true}).click();
await page.getByRole('heading',{name:'Research partner',exact:true}).waitFor();
await page.getByLabel('Filter library source').selectOption('personal');
assert.equal(await page.getByRole('heading',{name:'Product engineer',exact:true}).count(),0);
await page.getByLabel('Filter library source').selectOption('all');
await page.getByRole('button',{name:'Library table view',exact:true}).click();
assert.equal(await page.locator('table:visible tbody tr').count(),3);
await page.getByRole('button',{name:/^Skills/}).click();
assert.equal(await page.locator('table:visible tbody tr').count(),1);
await page.getByRole('button',{name:/^Agents/}).click();
await page.getByRole('button',{name:'Library card view',exact:true}).click();
await page.screenshot({path:'test-results/workforce/library.png',fullPage:true});
await page.getByRole('button',{name:'Teams Build & coordinate',exact:true}).click();
await page.getByRole('button',{name:'Create team',exact:true}).click();
await page.getByRole('button',{name:'Save team',exact:true}).click();
await page.getByText('Choose or create an agent for lead before saving your team.',{exact:true}).waitFor();
await page.getByRole('button',{name:'Create member from library',exact:true}).click();
await page.getByRole('button',{name:/Research partner.*Use template/}).click();
await page.getByRole('button',{name:'Create agent',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('select[aria-label="Saved agent"]')?.value==='created-agent');
await page.locator('summary').filter({hasText:'Team details'}).click();
await page.getByLabel('Team name',{exact:true}).fill('Studio');
await page.getByLabel('Team ID',{exact:true}).fill('studio');
await page.getByRole('button',{name:'Save team',exact:true}).click();
await page.waitForFunction(()=>window.savedTeams().some(t=>t.id==='studio' && t.roles[0].worker==='created-agent'));
await page.getByRole('button',{name:'Back to teams',exact:true}).click();
await page.getByRole('heading',{name:'Studio',exact:true}).waitFor();
await page.setViewportSize({width:620,height:900});
await page.screenshot({path:'test-results/workforce/narrow.png',fullPage:true});
assert(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth));
await page.evaluate(()=>document.documentElement.dataset.theme='light');
await page.screenshot({path:'test-results/workforce/light.png',fullPage:true});
assert.deepEqual(errors,[]);
console.log('PASS: team search, card/table views, solo filter, library source/category filters, missing-member validation, template creation and role assignment.');
} finally { await browser.close(); }
